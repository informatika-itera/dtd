// Generate M3 tonal color tokens from Airbnb seed colors and validate contrast.
// Run: bun scripts/gen-palette.ts  → writes src/theme/color.css
import {
  argbFromHex, hexFromArgb, themeFromSourceColor, Hct, TonalPalette, Blend,
} from '@material/material-color-utilities';
import { writeFileSync } from 'node:fs';

const SEED = {
  primary: '#ff385c', // Rausch
  secondary: '#92174d', // Plus
  tertiary: '#460479', // Luxe
  error: '#c13515',
};
// Airbnb neutrals override the generated ones.
const NEUTRAL = {
  surface: '#ffffff', onSurface: '#222222', onSurfaceVariant: '#6a6a6a',
  surfaceContainerLowest: '#ffffff', surfaceContainerLow: '#f7f7f7',
  surfaceContainer: '#f2f2f2', surfaceContainerHigh: '#ebebeb', surfaceContainerHighest: '#dddddd',
  outline: '#929292', outlineVariant: '#dddddd',
};

const pal = (hex: string) => TonalPalette.fromInt(argbFromHex(hex));
const P = pal(SEED.primary), S = pal(SEED.secondary), T = pal(SEED.tertiary), E = pal(SEED.error);
// Success / warning harmonized toward primary
const harm = (hex: string) => hexFromArgb(Blend.harmonize(argbFromHex(hex), argbFromHex(SEED.primary)));
// Low-chroma custom colors so state panels stay calm next to the brand palette.
const soft = (hex: string, chroma: number) => {
  const h = Hct.fromInt(argbFromHex(harm(hex)));
  return TonalPalette.fromHueAndChroma(h.hue, chroma);
};
const G = soft('#1a7f4b', 20), A = soft('#b45309', 24);
void themeFromSourceColor;

const t = (p: TonalPalette, n: number) => hexFromArgb(p.tone(n));
const accent = (name: string, p: TonalPalette, dark: boolean): Record<string, string> => ({
  [name]: t(p, dark ? 80 : 40), [`on-${name}`]: t(p, dark ? 20 : 100),
  [`${name}-container`]: t(p, dark ? 30 : 92), [`on-${name}-container`]: t(p, dark ? 90 : 20),
});
const roles = (dark: boolean): Record<string, string> => ({
  ...accent('primary', P, dark), ...accent('secondary', S, dark), ...accent('tertiary', T, dark),
  ...accent('success', G, dark), ...accent('warning', A, dark),
  ...accent('error', E, dark),
  ...(dark ? {
    surface: '#222222', 'on-surface': '#f2f2f2', 'on-surface-variant': '#bdbdbd',
    'surface-container-lowest': '#1b1b1b', 'surface-container-low': '#2b2b2b', 'surface-container': '#323232',
    'surface-container-high': '#3b3b3b', 'surface-container-highest': '#454545',
    outline: '#8c8c8c', 'outline-variant': '#4a4a4a', 'inverse-surface': '#f2f2f2', 'inverse-on-surface': '#222222',
  } : {
    surface: NEUTRAL.surface, 'on-surface': NEUTRAL.onSurface, 'on-surface-variant': NEUTRAL.onSurfaceVariant,
    'surface-container-lowest': NEUTRAL.surfaceContainerLowest, 'surface-container-low': NEUTRAL.surfaceContainerLow,
    'surface-container': NEUTRAL.surfaceContainer, 'surface-container-high': NEUTRAL.surfaceContainerHigh,
    'surface-container-highest': NEUTRAL.surfaceContainerHighest,
    outline: NEUTRAL.outline, 'outline-variant': NEUTRAL.outlineVariant, 'inverse-surface': '#222222', 'inverse-on-surface': '#f7f7f7',
  }),
  'brand-rausch': SEED.primary, // expressive accents only (large shapes, hero numerals)
});
// Airbnb error red stays as authored in light mode.
const light: Record<string, string> = { ...roles(false), error: SEED.error, 'on-error': '#ffffff' };
const dark = roles(true);

const lum = (hex: string) => {
  const c = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((x) => (x <= 0.03928 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};
const contrast = (a: string, b: string) => {
  const [x, y] = [lum(a), lum(b)].sort((m, n) => n - m);
  return (x + 0.05) / (y + 0.05);
};

// Every on-X must reach 4.5:1 on X; plus body text on all surfaces — in both schemes.
let fail = 0, checked = 0;
for (const [label, r] of [['light', light], ['dark', dark]] as [string, Record<string, string>][]) {
  const pairs: [string, string][] = [];
  for (const k of Object.keys(r)) if (r['on-' + k]) pairs.push(['on-' + k, k]);
  for (const sf of ['surface', 'surface-container-low', 'surface-container', 'surface-container-high'])
    for (const o of ['on-surface', 'on-surface-variant']) pairs.push([o, sf]);
  // accent text directly on surfaces (e.g. numerals, links)
  for (const a of ['primary', 'secondary', 'tertiary']) for (const sf of ['surface', 'surface-container-low']) pairs.push([a, sf]);
  for (const [fg, bg] of pairs) {
    checked++;
    const c = contrast(r[fg], r[bg]);
    if (c < 4.5) { fail++; console.error(`FAIL [${label}] ${fg} on ${bg}: ${c.toFixed(2)}`); }
  }
}
console.log(`contrast pairs checked: ${checked}, failures: ${fail}`);

const block = (r: Record<string, string>, ind = '') =>
  Object.entries(r).map(([k, v]) => `${ind}  --md-sys-color-${k}: ${v};`).join('\n');
const css = `/* GENERATED by scripts/gen-palette.ts — do not edit by hand. */
:root { color-scheme: light;
${block(light)}
}
:root[data-theme="dark"] { color-scheme: dark;
${block(dark)}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]):not([data-theme="dark"]) { color-scheme: dark;
${block(dark, '  ')}
  }
}
`;
writeFileSync(new URL('../src/theme/color.css', import.meta.url), css);
if (fail) process.exit(1);
